        date_str = f"{persian_weekday} {persian_day_text} {persian_month} {persian_year_text}/{persian_month_num}/{persian_day_num}"
        
        # مناسبت‌های شمسی و قمری
        shamsi_events = get_shamsi_events(year, month, day)
